let lastCongratulationIndex = -1;

export function getRandomCongratulationQuote(lang?: string): CongratulationQuote {
    let index: number;
    do {
        index = Math.floor(Math.random() * CONGRATULATION_QUOTES.length);
    } while (index === lastCongratulationIndex && CONGRATULATION_QUOTES.length > 1);

    lastCongratulationIndex = index;
    const quote = CONGRATULATION_QUOTES[index];
    if (lang === 'en') {
        return getLocalizedCongratulationQuote(quote, 'en');
    }
    return quote;
}

export function getLocalizedCongratulationQuote(quote: CongratulationQuote, lang?: string): CongratulationQuote {
    if (lang === 'en') {
        return {
            ...quote,
            title: quote.title_en || quote.title,
            message: quote.message_en || quote.message,
            highlight: quote.highlight_en || quote.highlight,
        };
    }
    return quote;
}
