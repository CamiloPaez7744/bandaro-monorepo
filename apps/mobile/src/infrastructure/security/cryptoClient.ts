import AsyncStorage from '@react-native-async-storage/async-storage';
import { Platform } from 'react-native';

const API_BASE_URL =
    process.env.EXPO_PUBLIC_API_URL ||
    (Platform.OS === 'android' ? 'http://10.0.2.2:8181' : 'http://localhost:8181');

const TOKEN_KEY = '@billar/auth/access_token';

export interface HandshakeInfo {
    keyId: string;
    publicKey: string;
    algorithm: string;
    timestamp: number;
}

export interface EncryptedPayload {
    _encrypted: true;
    keyId: string;
    encryptedKey: string;
    iv: string;
    authTag: string;
    ciphertext: string;
}

let cachedHandshake: HandshakeInfo | null = null;
let handshakePromise: Promise<HandshakeInfo | null> | null = null;

/**
 * Convert PEM public key to ArrayBuffer (SPKI DER)
 */
function pemToArrayBuffer(pem: string): ArrayBuffer {
    const b64 = pem
        .replace(/-----BEGIN PUBLIC KEY-----/, '')
        .replace(/-----END PUBLIC KEY-----/, '')
        .replace(/[\r\n\s]/g, '');
    const binary = atob(b64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
        bytes[i] = binary.charCodeAt(i);
    }
    return bytes.buffer;
}

function bufferToBase64(buffer: ArrayBuffer | Uint8Array): string {
    const bytes = buffer instanceof Uint8Array ? buffer : new Uint8Array(buffer);
    let binary = '';
    for (let i = 0; i < bytes.byteLength; i++) {
        binary += String.fromCharCode(bytes[i]);
    }
    return btoa(binary);
}

/**
 * Fetches the dynamic RSA public key generated by backend on startup
 */
export async function getHandshake(): Promise<HandshakeInfo | null> {
    if (cachedHandshake) return cachedHandshake;
    if (handshakePromise) return handshakePromise;

    handshakePromise = (async () => {
        try {
            const res = await fetch(`${API_BASE_URL}/security/handshake`);
            if (!res.ok) {
                console.warn('[cryptoClient] Handshake response not OK:', res.status);
                return null;
            }
            const data = await res.json();
            if (data.success && data.publicKey) {
                cachedHandshake = data;
                return data;
            }
            return null;
        } catch (error) {
            console.warn('[cryptoClient] Handshake network error, falling back:', error);
            return null;
        } finally {
            handshakePromise = null;
        }
    })();

    return handshakePromise;
}

/**
 * Encrypts a request body using hybrid RSA-OAEP + AES-256-GCM
 */
export async function encryptPayload(data: any): Promise<EncryptedPayload | any> {
    try {
        const cryptoObj = globalThis.crypto || (typeof window !== 'undefined' ? window.crypto : null);
        if (!cryptoObj || !cryptoObj.subtle) {
            // WebCrypto subtle not available, return unencrypted object
            return data;
        }

        const handshake = await getHandshake();
        if (!handshake) {
            return data;
        }

        const jsonStr = JSON.stringify(data);
        const encodedText = new TextEncoder().encode(jsonStr);

        // 1. Generate ephemeral AES-GCM 256-bit symmetric key
        const aesKey = await cryptoObj.subtle.generateKey(
            { name: 'AES-GCM', length: 256 },
            true,
            ['encrypt']
        );

        // 2. Generate 12-byte IV
        const iv = cryptoObj.getRandomValues(new Uint8Array(12));

        // 3. Encrypt data with AES-256-GCM (appends 16-byte authTag at the end)
        const encryptedBuffer = await cryptoObj.subtle.encrypt(
            { name: 'AES-GCM', iv },
            aesKey,
            encodedText
        );

        const encryptedBytes = new Uint8Array(encryptedBuffer);
        const ciphertextBytes = encryptedBytes.slice(0, encryptedBytes.length - 16);
        const authTagBytes = encryptedBytes.slice(encryptedBytes.length - 16);

        // 4. Import Server's RSA-OAEP Public Key
        const spkiDer = pemToArrayBuffer(handshake.publicKey);
        const rsaKey = await cryptoObj.subtle.importKey(
            'spki',
            spkiDer,
            { name: 'RSA-OAEP', hash: 'SHA-256' },
            false,
            ['encrypt']
        );

        // 5. Export raw AES key and encrypt with Server's RSA Public Key
        const rawAesKey = await cryptoObj.subtle.exportKey('raw', aesKey);
        const encryptedKeyBuffer = await cryptoObj.subtle.encrypt(
            { name: 'RSA-OAEP' },
            rsaKey,
            rawAesKey
        );

        return {
            _encrypted: true,
            keyId: handshake.keyId,
            encryptedKey: bufferToBase64(encryptedKeyBuffer),
            iv: bufferToBase64(iv),
            authTag: bufferToBase64(authTagBytes),
            ciphertext: bufferToBase64(ciphertextBytes),
        };
    } catch (error) {
        console.warn('[cryptoClient] Failed to encrypt payload, sending plaintext fallback:', error);
        return data;
    }
}

/**
 * Universal secure API client fetcher with automatic hybrid encryption
 */
export async function apiFetch(path: string, options: RequestInit = {}): Promise<Response> {
    const url = path.startsWith('http') ? path : `${API_BASE_URL}${path}`;
    const token = await AsyncStorage.getItem(TOKEN_KEY);

    const headers: Record<string, string> = {
        'Content-Type': 'application/json',
        ...(options.headers as Record<string, string> || {}),
    };

    if (token && !headers['Authorization']) {
        headers['Authorization'] = `Bearer ${token}`;
    }

    let body = options.body;
    if (body && typeof body === 'object') {
        const encrypted = await encryptPayload(body);
        body = JSON.stringify(encrypted);
    } else if (body && typeof body === 'string') {
        try {
            const parsed = JSON.parse(body);
            const encrypted = await encryptPayload(parsed);
            body = JSON.stringify(encrypted);
        } catch {
            // Not a JSON string, leave as is
        }
    }

    const response = await fetch(url, {
        ...options,
        headers,
        body,
    });

    // If server restarted and returned reHandshakeRequired, clear cache
    if (response.status === 400) {
        try {
            const clone = response.clone();
            const errData = await clone.json();
            if (errData.reHandshakeRequired) {
                cachedHandshake = null;
            }
        } catch {
            // Ignore
        }
    }

    return response;
}
